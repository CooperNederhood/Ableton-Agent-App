#!/usr/bin/env python3
"""Explicit offline rebuild + promotion of ONLY the enumerated native bundle."""
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
REPO = ROOT.parents[2]
ARTIFACTS = ROOT / "node_modules/.native-mel"
BUNDLE = "listener.mel~.mxo"
FILES = (
    "Contents/Info.plist",
    "Contents/MacOS/listener.mel~",
    "Contents/Resources/licenses/flucoma-BSD3.txt",
    "Contents/Resources/licenses/HISSTools-BSD3.txt",
    "Contents/Resources/licenses/Eigen-MPL2.txt",
    "Contents/Resources/licenses/foonathan-zlib.txt",
    "Contents/Resources/licenses/Max-SDK-license.txt",
    "Contents/Resources/licenses/source-pins.json",
)
SOURCES = (
    "CMakeLists.txt", "Info.plist.in", "dependencies.json", "mel_engine.hpp",
    "max_external.cpp", "build.py", "publish.py",
)
DEST = ROOT.parent / "dependencies/flucoma"
PIN_FILE = REPO / "packages/shared/src/native-mel-pins.ts"


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def output(*args):
    return subprocess.check_output(args, text=True).strip()


def regular(path):
    for ancestor in [path, *path.parents]:
        if ancestor.is_symlink():
            sys.exit(f"Symlink denied: {ancestor}")
    if not path.is_file():
        sys.exit(f"Missing regular file: {path}")
    return path.read_bytes()


def source_inputs():
    return [
        {"path": (ROOT / name).relative_to(REPO).as_posix(),
         "bytes": len(raw), "sha256": digest(raw)}
        for name in SOURCES for raw in [regular(ROOT / name)]
    ]


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--publish", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    before = source_inputs()
    subprocess.run([sys.executable, str(ROOT / "build.py"), "--universal"], check=True)
    if source_inputs() != before:
        sys.exit("Native sources changed during build")
    bundle = ARTIFACTS / "build/universal" / BUNDLE
    expected = set(FILES)
    # Inventory traversal is inspection only. Publication below reads exact FILES.
    actual = {p.relative_to(bundle).as_posix() for p in bundle.rglob("*")
              if p.is_file() or p.is_symlink()}
    if actual != expected:
        sys.exit(f"Unexpected native bundle inventory: {sorted(actual ^ expected)}")
    binary = bundle / "Contents/MacOS/listener.mel~"
    if set(output("lipo", "-archs", str(binary)).split()) != {"arm64", "x86_64"}:
        sys.exit("Both native architecture slices are required")
    payload = {f"{BUNDLE}/{name}": regular(bundle / name) for name in FILES}
    provenance = {
        "schema": "listener-mel-native-build/v1",
        "producerAbi": 2,
        "profile": "24/20/20000/normalize0/scale0/2048/2048/2048/hann",
        "architectures": ["arm64", "x86_64"],
        "deploymentTarget": "11.0",
        "compiler": output("clang++", "--version").splitlines()[0],
        "sdk": output("xcrun", "--show-sdk-version"),
        "cmake": json.loads(regular(ROOT / "dependencies.json"))["cmake"],
        "dependencies": json.loads(regular(ROOT / "dependencies.json"))["dependencies"],
        "inputs": before,
        "binarySha256": digest(payload[f"{BUNDLE}/Contents/MacOS/listener.mel~"]),
        "hostQualified": False,
    }
    payload["listener-mel-build.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    pins = [[name, len(raw), digest(raw)] for name, raw in sorted(payload.items())]
    pin_text = (
        "// Generated by native-mel-adapter/publish.py; ordinary builds never repin.\n"
        "// prettier-ignore\nexport const NATIVE_MEL_DEPENDENCY_PINS = "
        + json.dumps(pins, indent=2) + " as const;\n\n"
        "// prettier-ignore\nexport const NATIVE_MEL_SOURCE_INPUTS = "
        + json.dumps(before, indent=2) + " as const;\n"
    ).encode()
    if args.check:
        for name, raw in payload.items():
            if regular(DEST / name) != raw:
                sys.exit(f"Rebuild does not reproduce pinned resource: {name}")
        if regular(PIN_FILE) != pin_text:
            sys.exit("Rebuild does not reproduce source-linked pin table")
        print("Universal rebuild reproduces every pinned bundle/provenance byte.")
        return
    for name, raw in payload.items():
        path = DEST / name
        for ancestor in [path, *path.parents]:
            if ancestor.is_symlink():
                sys.exit(f"Symlink denied: {ancestor}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
        path.chmod(0o755 if name.endswith("/MacOS/listener.mel~") else 0o644)
    PIN_FILE.write_bytes(pin_text)
    print(json.dumps({"files": pins, "binarySha256": provenance["binarySha256"]}, indent=2))


if __name__ == "__main__":
    main()
