import { readFile, writeFile } from "node:fs/promises";

const sourceUrl = new URL("../config/product-versions.json", import.meta.url);
const typescriptUrl = new URL(
  "../packages/shared/src/product-versions.generated.ts",
  import.meta.url,
);
const protocolUrl = new URL(
  "../packages/protocol/src/version.generated.ts",
  import.meta.url,
);
const projectStateUrl = new URL(
  "../packages/project-state/src/version.generated.ts",
  import.meta.url,
);
const pythonUrl = new URL(
  "../remote-script/AbletonAgent/version.py",
  import.meta.url,
);

const versions = JSON.parse(await readFile(sourceUrl, "utf8"));
const typescript = `// Generated by scripts/generate-product-versions.mjs. Do not edit.
export const PRODUCT_VERSIONS = {
  app: ${JSON.stringify(versions.app)},
  remoteScript: ${JSON.stringify(versions.remoteScript)},
  protocol: ${versions.protocol},
  database: ${versions.database},
  minimumRemoteScript: ${JSON.stringify(versions.minimumRemoteScript)},
  supportedLive: {
${Object.entries(versions.supportedLive)
  .map(
    ([major, minimum]) =>
      `    ${JSON.stringify(major)}: ${JSON.stringify(minimum)},`,
  )
  .join("\n")}
  },
} as const;
`;
const protocol = `// Generated by scripts/generate-product-versions.mjs. Do not edit.
export const GENERATED_PROTOCOL_VERSION = ${versions.protocol} as const;
`;
const projectState = `// Generated by scripts/generate-product-versions.mjs. Do not edit.
export const GENERATED_DATABASE_VERSION = ${versions.database} as const;
`;
const python = `"""Generated by scripts/generate-product-versions.mjs. Do not edit."""

REMOTE_SCRIPT_VERSION = ${JSON.stringify(versions.remoteScript)}
PROTOCOL_VERSION = ${versions.protocol}
`;

const outputs = [
  [typescriptUrl, typescript],
  [protocolUrl, protocol],
  [projectStateUrl, projectState],
  [pythonUrl, python],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [url, content] of outputs) {
  if (check) {
    const current = await readFile(url, "utf8").catch(() => "");
    if (current !== content) {
      console.error(`${url.pathname} is not synchronized`);
      stale = true;
    }
  } else {
    await writeFile(url, content);
  }
}

const manifests = [
  new URL("../package.json", import.meta.url),
  new URL("../apps/desktop/package.json", import.meta.url),
];
for (const url of manifests) {
  const manifest = JSON.parse(await readFile(url, "utf8"));
  if (manifest.version !== versions.app) {
    console.error(`${url.pathname} version must be ${versions.app}`);
    stale = true;
  }
}

if (stale) process.exitCode = 1;
